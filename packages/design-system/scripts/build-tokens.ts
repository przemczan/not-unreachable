/**
 * Generates src/tokens.css, src/theme.css and the README's token reference from tokens/tokens.json.
 * The outputs are committed; `--check` fails when one differs from what this script would write.
 *
 *   node scripts/build-tokens.ts           write the files
 *   node scripts/build-tokens.ts --check   exit 1 if any is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { exposureOf, radiusRoles, resetNamespaces, type Exposure, type GroupKey } from "./theme-mapping.ts";
import { allTokens, cssValue, isThemed, loadTokenSource, scalarGroups, typeStyles, type Token, type TokenSource } from "./token-source.ts";

const header = "/* Generated by scripts/build-tokens.ts from tokens/tokens.json. Edit those, then run `pnpm tokens`. */";

/** A usage note as a CSS comment; `*\/` can't appear in one. */
function comment(text: string): string {
  return `/* ${text.replaceAll("*/", "* /")} */`;
}

function groupedTokens(source: TokenSource): { group: GroupKey; token: Token }[] {
  return [
    ...source.color.tokens.map((token) => ({ group: "color" as const, token })),
    ...scalarGroups.flatMap(({ key }) => source[key].tokens.map((token) => ({ group: key, token }))),
  ];
}

/** Every token with how it reaches Tailwind; throws on a token no mapping covers. */
export function exposures(source: TokenSource): { token: Token; exposure: Exposure }[] {
  return groupedTokens(source).map(({ group, token }) => ({ token, exposure: exposureOf(group, token) }));
}

/** The font size token whose value a type style uses, so the shorthand refers to it. */
function fontSizeVariable(source: TokenSource, size: string): string {
  const token = source.fontSize.tokens.find((candidate) => candidate.value === size);
  if (token === undefined) throw new Error(`No font size token has the value ${size}.`);
  return `var(--${token.name})`;
}

function letterSpacingVariable(source: TokenSource, spacing: string | undefined): string {
  const value = spacing ?? "0";
  const token = source.letterSpacing.tokens.find((candidate) => candidate.value === value);
  if (token === undefined) throw new Error(`No letter spacing token has the value ${value}.`);
  return `var(--${token.name})`;
}

export function renderTokensCss(source: TokenSource): string {
  const light = allTokens(source).map((token) => {
    const value = isThemed(token.value) ? token.value.light : token.value;
    return `  --${token.name}: ${cssValue(value)}; ${comment(token.usage)}`;
  });
  const dark = allTokens(source).flatMap((token) => (isThemed(token.value) ? [`  --${token.name}: ${cssValue(token.value.dark)};`] : []));
  const families = Object.entries(source.type.families).map(([key, stack]) => `  --font-${key}: ${stack};`);
  const typeRoles = typeStyles(source).flatMap((style) => [
    `  --text-${style.name}: ${style.fontWeight} ${fontSizeVariable(source, style.fontSize)}/${style.lineHeight} var(--font-${style.family}); ${comment(style.usage)}`,
    `  --type-${style.name}: var(--text-${style.name});`,
  ]);
  const radii = Object.entries(radiusRoles).map(([role, size]) => `  --${role}: var(--${size});`);
  return [
    header,
    ':root,\n[data-theme="light"] {',
    ...light,
    "",
    "  /* Font families */",
    ...families,
    "",
    "  /* Type roles: font shorthands, used through the type-* utilities */",
    ...typeRoles,
    "",
    "  /* Radius roles */",
    ...radii,
    "}",
    "",
    '[data-theme="dark"] {',
    ...dark,
    "}",
    "",
  ].join("\n");
}

function themeBlock(source: TokenSource): string[] {
  const variables = exposures(source).flatMap(({ token, exposure }) =>
    exposure.kind === "theme" ? [`  ${exposure.variable}: var(--${token.name});`] : [],
  );
  const families = Object.entries(source.type.families).map(([key, stack]) => `  --font-${key}: ${stack};`);
  const radii = Object.keys(radiusRoles).map((role) => `  --${role}: var(--${role});`);
  return [
    // `inline` puts var(--token) straight into each utility, and `reference` emits no Tailwind variable,
    // so the tokens.css variables (which change per theme) are the only ones on the page.
    "@theme inline reference {",
    ...resetNamespaces.map((namespace) => `  ${namespace}: initial;`),
    ...families,
    ...radii,
    ...variables,
    "  --animate-spin: nu-spin 1s linear infinite;",
    "  --default-transition-duration: var(--duration-fast);",
    "  --default-transition-timing-function: var(--ease-out);",
    "}",
  ];
}

function fontFaces(source: TokenSource): string[] {
  return source.type.fonts.flatMap((font) => [
    "@font-face {",
    `  font-family: "${font.family}";`,
    `  src: url("./${font.file}") format("woff2");`,
    `  font-weight: ${font.weight};`,
    `  font-style: ${font.style};`,
    "  font-display: swap;",
    "}",
  ]);
}

function typeUtilities(source: TokenSource): string[] {
  return typeStyles(source).flatMap((style) => [
    `@utility type-${style.name} {`,
    `  font: var(--type-${style.name});`,
    `  letter-spacing: ${letterSpacingVariable(source, style.letterSpacing)};`,
    ...(style.name === "overline" ? ["  text-transform: uppercase;"] : []),
    "}",
  ]);
}

function tokenUtilities(source: TokenSource): string[] {
  return exposures(source).flatMap(({ token, exposure }) =>
    exposure.kind === "utility" ? [`@utility ${exposure.utility} {`, `  ${exposure.property}: var(--${token.name});`, "}"] : [],
  );
}

