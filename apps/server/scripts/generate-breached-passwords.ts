// Regenerates src/modules/accounts/breached-passwords.ts from SecLists' NCSC top-100k list (threat model, T1).
//
//   node scripts/generate-breached-passwords.ts            downloads the list
//   node scripts/generate-breached-passwords.ts <file>     reads a copy already downloaded
//
// Only entries of 12–256 characters are kept: the password rules refuse shorter and longer ones anyway.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt";
const MIN_LENGTH = 12;
const MAX_LENGTH = 256;

const target = fileURLToPath(new URL("../src/modules/accounts/breached-passwords.ts", import.meta.url));

async function readSource(file: string | undefined): Promise<string> {
  if (file !== undefined) return readFileSync(file, "utf8");
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Download failed: ${response.status} ${response.statusText}`);
  return response.text();
}

/** Escapes what a template literal would otherwise interpret. */
function escapeForTemplate(text: string): string {
  return text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

function keptEntries(source: string): string[] {
  const entries = source
    .split("\n")
    .map((line) => line.replace(/\r$/, ""))
    .filter((line) => line.length >= MIN_LENGTH && line.length <= MAX_LENGTH);
  return [...new Set(entries)];
}

function moduleText(entries: readonly string[]): string {
  return `// Generated by scripts/generate-breached-passwords.ts; do not edit by hand.
//
// Source: SecLists, Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt
//   ${SOURCE_URL}
//   https://github.com/danielmiessler/SecLists, MIT licence (Copyright (c) 2018 Daniel Miessler).
//   The NCSC list derives from Have I Been Pwned's Pwned Passwords.
// Filter: only the ${entries.length} entries of ${MIN_LENGTH}–${MAX_LENGTH} characters, as shorter and longer passwords are refused anyway.
// Compared case-sensitively, as the list is.

const list = \`${entries.map(escapeForTemplate).join("\n")}\`;

/** Breached passwords a new password must not be (threat model, T1). */
export const breachedPasswords: ReadonlySet<string> = new Set(list.split("\\n"));
`;
}

const entries = keptEntries(await readSource(process.argv[2]));
writeFileSync(target, moduleText(entries));
console.log(`generate-breached-passwords: wrote ${entries.length} entries to ${target}`);
