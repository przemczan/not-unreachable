export function renderThemeCss(source: TokenSource): string {
  return [
    header,
    '@import "tailwindcss";',
    '@import "./tokens.css";',
    "",
    "/* The theme follows data-theme on <html>, not the system setting (see AppShell's theme switch). */",
    "@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));",
    "",
    ...fontFaces(source),
    "",
    ...themeBlock(source),
    "",
    "@keyframes nu-spin {",
    "  to {",
    "    transform: rotate(360deg);",
    "  }",
    "}",
    "",
    ...typeUtilities(source),
    "",
    ...tokenUtilities(source),
    "",
    baseRules,
    "",
  ].join("\n");
}

function inCode(value: string): string {
  return `\`${value}\``;
}

function displayValue(token: Token): string {
  return isThemed(token.value) ? `${inCode(token.value.light)} / ${inCode(token.value.dark)}` : inCode(token.value);
}

function exposureNote(exposure: Exposure): string {
  if (exposure.kind === "theme") return inCode(exposure.variable);
  if (exposure.kind === "utility") return inCode(exposure.utility);
  return `– ${exposure.reason}`;
}

export const referenceStart = "<!-- token-reference:start (generated by scripts/build-tokens.ts) -->";
export const referenceEnd = "<!-- token-reference:end -->";

/** The README's token reference: every token with its value, usage and Tailwind mapping. */
export function renderTokenReference(source: TokenSource): string {
  const byName = new Map(exposures(source).map(({ token, exposure }) => [token.name, exposure]));
  const table = (tokens: readonly Token[]) => [
    "| Token | Value (light / dark) | Usage | In Tailwind |",
    "| --- | --- | --- | --- |",
    ...tokens.map((token) => {
      const exposure = byName.get(token.name);
      if (exposure === undefined) throw new Error(`No exposure for ${token.name}.`);
      return `| \`--${token.name}\` | ${displayValue(token)} | ${token.usage.replaceAll("|", "\\|")} | ${exposureNote(exposure).replaceAll("|", "\\|")} |`;
    }),
  ];
  const types = typeStyles(source).map(
    (style) =>
      `| \`type-${style.name}\` | ${style.fontWeight} ${style.fontSize}/${style.lineHeight} ${style.family}${style.letterSpacing === undefined ? "" : `, ${style.letterSpacing}`} | ${style.usage} |`,
  );
  return [
    referenceStart,
    "",
    "### Colours",
    "",
    ...table(source.color.tokens),
    "",
    "### Type roles",
    "",
    "| Class | Font | Usage |",
    "| --- | --- | --- |",
    ...types,
    "",
    ...scalarGroups.flatMap(({ key, title }) => [`### ${title}`, "", ...table(source[key].tokens), ""]),
    referenceEnd,
  ].join("\n");
}

export function withTokenReference(readme: string, reference: string): string {
  const start = readme.indexOf(referenceStart);
  const end = readme.indexOf(referenceEnd);
  if (start === -1 || end === -1 || end < start) throw new Error("README.md has no token reference markers.");
  return readme.slice(0, start) + reference + readme.slice(end + referenceEnd.length);
}

const packageRoot = new URL("../", import.meta.url);

export interface Output {
  readonly path: string;
  readonly expected: string;
}

/** Formats as the repo's Prettier config does, so `pnpm format:check` and `--check` agree. */
async function formatted(path: string, text: string): Promise<string> {
  const options = await resolveConfig(path);
  return format(text, { ...options, filepath: path });
}

/** The files the generator owns, with the text each should have. */
export async function outputs(source: TokenSource = loadTokenSource()): Promise<Output[]> {
  const readmePath = fileURLToPath(new URL("README.md", packageRoot));
  const files = [
    { path: fileURLToPath(new URL("src/tokens.css", packageRoot)), text: renderTokensCss(source) },
    { path: fileURLToPath(new URL("src/theme.css", packageRoot)), text: renderThemeCss(source) },
    { path: readmePath, text: withTokenReference(readFileSync(readmePath, "utf8"), renderTokenReference(source)) },
  ];
  return Promise.all(files.map(async ({ path, text }) => ({ path, expected: await formatted(path, text) })));
}

function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

/** The outputs whose file differs from what the generator writes; `read` gives a file's text (tests pass their own). */
export async function staleOutputs(source?: TokenSource, read: (path: string) => string = readOrEmpty): Promise<string[]> {
  return (await outputs(source)).filter((output) => read(output.path) !== output.expected).map((output) => output.path);
}

async function main(argv: readonly string[]): Promise<number> {
  if (argv.includes("--check")) {
    const stale = await staleOutputs();
    for (const path of stale)
      console.error(`${path} is out of date with tokens/tokens.json: run \`pnpm tokens\` in packages/design-system.`);
    return stale.length === 0 ? 0 : 1;
  }
  for (const output of await outputs()) writeFileSync(output.path, output.expected);
  return 0;
}

if (import.meta.main) {
  process.exitCode = await main(process.argv.slice(2));
}
